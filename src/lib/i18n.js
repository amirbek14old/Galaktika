export function tr(lang, key, vars = {}) {
  const e = D[key];
  const s = e ? (e[IDX[lang] ?? 0] || e[0]) : key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
}
/** Plural form for a "one|few|many" (ru) or "one|other" (en) or single (uz) entry. */
export function plural(lang, key, n) {
  const forms = tr(lang, key).split('|');
  if (lang === 'ru') { const m = n % 10, h = n % 100; return forms[m === 1 && h !== 11 ? 0 : m >= 2 && m <= 4 && (h < 10 || h >= 20) ? 1 : 2] || forms[0]; }
  if (lang === 'en') return n === 1 ? forms[0] : forms[1] || forms[0];
  return forms[0];
}
export function useT() {
  const lang = useStore((s) => s.lang || 'ru');
  const t = (k, v) => tr(lang, k, v);
  t.lang = lang;
  t.pl = (key, n) => plural(lang, key, n);
  t.list = (k) => tr(lang, k).split('|');
  return t;
}
