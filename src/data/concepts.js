export const concept = (id) => CONCEPTS.find((c) => c.id === id);

/** All prerequisites (transitive) of a concept. */
export function ancestors(id, acc = new Set()) {
  for (const p of concept(id)?.pre || []) { if (!acc.has(p)) { acc.add(p); ancestors(p, acc); } }
  return acc;
}

